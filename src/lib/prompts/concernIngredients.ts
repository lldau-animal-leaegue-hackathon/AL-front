/**
 * "고민 → 효과 있는 성분" 프롬프트 — **서버 전용**. 이 파일이 정본이다.
 *
 * ⛔ **웹 도구를 쓰지 않는다**(사용자 결정 2026-08-19, concern-flow Q3).
 * 성분-효능은 잘 알려진 지식이라 검색 없이도 답이 안정적이고, 10~30초로 끝난다.
 * 실측에서 성분 관련 질의는 웹 검색을 켜도 **모델이 도구를 호출하지 않았다**(3/3) —
 * 도구를 주면 "검색해서 찾았다"는 인상만 주고 실제로는 기억으로 답한다. 차라리 명시적으로 끈다.
 *
 * ⚠️ 대신 **지어내지 않게** 하는 책임이 프롬프트에 온다:
 *  - 규칙 2: 확신이 없으면 넣지 말 것(기존 프롬프트 3종과 같은 규율)
 *  - 규칙 5: 진단·치료 표현 금지. 화면에도 "의학적 조언이 아니다"를 고정한다
 */

export type ConcernIngredientsInput = {
  /** 사용자가 적은 피부 고민. 예: "모공이 넓고 각질이 일어나요" */
  wonder: string;
};

/** 프롬프트 규칙 3 — 성분 상한. 화면·검증이 같은 값을 봐야 해서 내보낸다. */
export const MAX_CONCERN_INGREDIENTS = 6;

export function buildConcernIngredientsPrompt(
  input: ConcernIngredientsInput,
): string {
  return `당신은 화장품 성분에 밝은 피부 미용 전문가입니다.
사용자가 적은 피부 고민을 읽고, 그 고민에 도움이 된다고 널리 알려진 화장품 성분을 골라 주세요.

피부 고민:
${input.wonder}

규칙:
1. 화장품에 실제로 쓰이는 성분만 고르세요. 의약품 성분이나 시술은 넣지 마세요.
2. 널리 알려진 성분만 고르세요. 효과가 확실하지 않거나 근거가 약하면 넣지 마세요. 개수를 채우려고 억지로 넣지 마세요.
3. 최대 ${MAX_CONCERN_INGREDIENTS}개까지입니다. 고민과 관련이 깊은 순서로 정렬하세요.
4. effect 는 그 성분이 이 고민에 어떻게 도움이 되는지 한 문장으로 적으세요. 40자 이내로 간결하게 쓰세요.
5. **진단하거나 치료를 약속하지 마세요.** "치료한다", "낫는다", "없어진다" 같은 표현을 쓰지 말고 "도움이 될 수 있다", "완화에 쓰인다" 처럼 적으세요.
6. caution 에는 그 성분을 쓸 때 널리 알려진 주의점이 있을 때만 한 문장으로 적고, 없으면 null 로 두세요. (예: 레티놀은 밤에 쓰고 자외선 차단을 함께)
7. 입력이 피부 고민이 아니거나 성분을 고를 수 없으면 ingredients 를 빈 배열([])로 반환하세요.
8. 반드시 아래 JSON 형식으로만 응답하세요. 설명, 코드블록 표시, 추가 텍스트를 포함하지 마세요.

출력 형식 (값은 한국어):
{
  "ingredients": [
    {
      "name": string, // 성분 이름
      "effect": string, // 이 고민에 어떻게 도움이 되는지 (40자 이내)
      "caution": string | null // 알려진 주의점. 없으면 null
    }
  ]
}`;
}
