/**
 * "제품 후보 검색" 프롬프트 — **서버 전용**. 이 파일이 정본이다.
 *
 * 성분 추출(`ingredients.ts`)과 달리 **웹 검색 도구를 쓴다.** 근거가 모델의 기억이 아니라
 * 실제 화해(hwahae.co.kr) 검색 결과라, 이 레포가 지켜 온 "지어내지 않는다" 원칙과 맞는다.
 *
 * ⚠️ 아래 규칙은 전부 **실측으로 얻은 제약**이다(2026-08-18). 완화하면 느려지거나 틀린다:
 *  - 상세 페이지(`/goods/{id}`)는 **403**(AWS WAF)이다. 열려고 하면 실패하고,
 *    폴백을 15번씩 탐색하다 180초까지 갔다. 금지하면 **18~37초**로 끝난다.
 *  - 다른 사이트 폴백은 **구버전 성분·다른 제품**을 준다. 검색 단계에서는 막는다.
 *  - 제품명에 판촉 문구가 섞인다:
 *    `[only화해][NEW]다이브인 히알루론산 세럼100ml 기획(+토너50ml+수딩20ml)`.
 *
 * ⛔ **가격은 요구하지 않는다**(사용자 결정 2026-08-18). 실측에서 검색어에 따라
 *    0/5 또는 5/5 로 갈렸고, 나오더라도 정가가 아니라 사은품 묶음 "최저가"였다.
 *    재현되지 않는 값을 화면에 정가처럼 보여 줄 수 없다.
 *
 * ✅ **이미지는 요구한다**(2026-08-19 실측). 후보 4/4 에서 `img.hwahae.co.kr` 의 썸네일
 *    주소가 나왔고, Referer 없이도 200 이었다(상세 페이지의 403 은 CDN 에 적용되지 않는다).
 *    ⚠️ 다만 **여기서 온 주소는 LLM 이 만든 값**이다. 라우트가 호스트를 검증한다(`src/lib/images.ts`).
 */

export type ProductSearchInput = {
  /** 사용자가 입력한 검색어. 제품명 일부나 브랜드만 넣어도 된다. */
  query: string;
};

/** 프롬프트 규칙 4 — 후보 상한. 화면과 검증이 같은 값을 봐야 해서 여기서 내보낸다. */
export const MAX_CANDIDATES = 5;

export function buildProductSearchPrompt(input: ProductSearchInput): string {
  const query = input.query.trim();

  return `당신은 화장품 정보를 찾아 주는 도우미입니다.
아래 검색어로 화해(hwahae.co.kr)에서 실제 판매 중인 제품 후보를 찾아 주세요.

검색어: ${query}

규칙:
1. WebFetch 로 https://www.hwahae.co.kr/search?q=${encodeURIComponent(query)} 페이지를 읽고, 그 페이지에 실제로 있는 제품만 후보로 삼으세요.
2. 개별 제품 상세 페이지(/goods/... )는 접근이 차단되어 있습니다. 절대 열지 마세요. 열어도 실패하고 시간만 소모합니다.
3. 화해에서 찾지 못하면 다른 사이트로 넘어가지 말고 candidates 를 빈 배열([])로 반환하세요. 다른 사이트의 정보는 제품이 다르거나 오래된 경우가 많습니다.
4. 후보는 최대 ${MAX_CANDIDATES}개입니다. 검색어와 관련 없는 제품은 넣지 마세요.
5. product_name 에는 **제품 본래 이름만** 적으세요. 아래 같은 판촉 표기는 모두 제거합니다.
   - 대괄호 표기: [NEW], [only화해], [단독] 등
   - 기획/세트/증정/사은품 표기와 괄호 묶음: "기획", "더블기획", "(+토너 50ml)", "(+화장솜)"
   - 용량 표기는 product_name 에서 빼고 volume 에 넣으세요.
   예: "[only화해][NEW]다이브인 히알루론산 세럼100ml 기획(+토너50ml)" → product_name: "다이브인 히알루론산 세럼", volume: "100ml"
6. brand 에는 제조사(브랜드)명을 적으세요. 페이지에서 확인되지 않으면 null 로 두세요. 추측하지 마세요.
7. volume 은 페이지에 명시된 용량만 적으세요. 없으면 null 로 두세요. 추정하지 마세요.
8. 같은 제품의 용량만 다른 항목이 여러 개면 대표 1개만 남기세요.
9. image_url 에는 그 제품의 이미지 주소를 페이지에서 **실제로 확인한 경우에만** 넣으세요. 확인되지 않으면 null 로 두세요. 주소를 추측하거나 만들어내지 마세요.
10. 반드시 아래 JSON 형식으로만 응답하세요. 설명, 코드블록 표시, 추가 텍스트를 포함하지 마세요.

출력 형식:
{
  "candidates": [
    {
      "product_name": string, // 판촉 문구를 제거한 제품 이름
      "brand": string | null, // 제조사(브랜드). 모르면 null
      "volume": string | null, // 용량. 페이지에 없으면 null
      "image_url": string | null // 제품 이미지 주소. 확인 못 하면 null
    }
  ]
}`;
}
